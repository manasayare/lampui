/**
 * Generates project/tokens/system-theme.css.
 *
 * The token architecture is `:root` = light, `[data-theme="dark"]` = dark, which
 * covers an app that owns its theme switch and nothing else. A viewer has three
 * states, not two: explicit light, explicit dark, and — the most common —
 * "system", where nothing is stamped on the root at all. In that third state the
 * tokens resolve light no matter what the operating system asked for.
 *
 * This copies every `[data-theme="dark"]` block in the token and component CSS
 * into `@media (prefers-color-scheme: dark) { :root:not([data-theme="light"]) }`,
 * so an unstamped document follows the OS while an explicit `data-theme="light"`
 * still wins over a dark OS, and `data-theme="dark"` still wins over a light one.
 *
 * Generated rather than hand-written so the dark palette stays authored in
 * exactly one place. Re-run via `npm run build`.
 */
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const PROJECT = join(ROOT, 'project');

const walk = (dir, out = []) => {
  for (const e of readdirSync(dir)) {
    const f = join(dir, e);
    if (statSync(f).isDirectory()) walk(f, out);
    else if (f.endsWith('.css')) out.push(f);
  }
  return out;
};

const files = walk(join(PROJECT, 'tokens'))
  .concat(walk(join(PROJECT, 'components')))
  .filter((f) => !f.endsWith('system-theme.css'))
  .sort();

/**
 * Pulls out `[data-theme="dark"] { … }` blocks. The CSS here has no nested
 * braces inside these blocks (they are flat custom-property declarations), so
 * matching to the first `}` is sufficient and avoids pulling in a parser.
 */
const blocks = [];
for (const file of files) {
  /* Comments are stripped first: colors.css documents the architecture with the
     literal text `[data-theme="dark"] = dark`, which the selector match would
     otherwise pick up as a rule. */
  const css = readFileSync(file, 'utf8').replace(/\/\*[\s\S]*?\*\//g, '');
  const re = /\[data-theme="dark"\]([^{};]*)\{([^}]*)\}/g;
  let m;
  while ((m = re.exec(css))) {
    const suffix = m[1].trim();
    const body = m[2].replace(/\s+$/, '');
    blocks.push({
      file: relative(PROJECT, file).split('\\').join('/'),
      /* `[data-theme="dark"] .lamp-x` has to become
         `:root:not([data-theme="light"]) .lamp-x`, not just the root. */
      selector: ':root:not([data-theme="light"])' + (suffix ? ' ' + suffix : ''),
      body,
    });
  }
}

const out = [
  '/* GENERATED by tools/build-system-theme.mjs — do not edit.',
  ' *',
  ' * Dark tokens for viewers who have not stamped a theme on the document, which',
  ' * is the default state. Without this, "system: dark" renders the light palette.',
  ' *',
  ' * Guarded with :not([data-theme="light"]) so an explicit light choice still',
  ' * beats a dark OS, and the plain [data-theme="dark"] rules in the source files',
  ' * still beat a light one. The dark palette itself is authored once, in those',
  ' * source files; this is a copy of it under a different condition. */',
  '',
  '@media (prefers-color-scheme: dark) {',
];

let lastFile = null;
for (const b of blocks) {
  if (b.file !== lastFile) {
    out.push('');
    out.push('  /* ' + b.file + ' */');
    lastFile = b.file;
  }
  out.push('  ' + b.selector + ' {');
  for (const line of b.body.split('\n')) {
    const t = line.trim();
    if (t) out.push('    ' + t);
  }
  out.push('  }');
}
out.push('}');
out.push('');

writeFileSync(join(PROJECT, 'tokens', 'system-theme.css'), out.join('\n'));

const decls = blocks.reduce((a, b) => a + b.body.split(';').filter((s) => s.trim()).length, 0);
console.log(
  'system-theme.css  ' + blocks.length + ' dark block(s), ' + decls
  + ' declarations mirrored to prefers-color-scheme',
);
